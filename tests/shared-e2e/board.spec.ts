import { test, expect, type Page } from "@playwright/test"
import { addCard, board, card, choose, editor, openBoardAction, signIn, startCard } from "../helpers/workspace"

test.beforeEach(async ({ request, page }) => {
  let state = await (await request.get("/api/board", { headers: { Authorization: "Bearer browser-api-token-2026-at-least-32-characters" } })).json()
  for (const card of state.board.cards) {
    for (const type of card.archived ? ["delete"] : ["archive", "delete"]) {
      const response = await request.post("/api/board", { headers: { Authorization: "Bearer browser-api-token-2026-at-least-32-characters" }, data: { revision: state.revision, action: { type, id: card.id } } })
      expect(response.ok()).toBe(true)
      state = await response.json()
    }
  }
  await signIn(page)
})

/* A workspace card opens from the keyboard as well as by clicking it. */
const openCard = (page: Page, title: string) => card(page, title).press("Enter")
const titles = (page: Page, column?: string) => page.locator(`${column ? `[data-column="${column}"] ` : ""}.agora-card-title`)

test("independent browsers share edits, moves, archive/restore/delete and conflict-safe drafts", async ({ page, browser }) => {
  const secondContext = await browser.newContext()
  const second = await secondContext.newPage()
  await signIn(second, "http://127.0.0.1:4290/")
  await addCard(page, "Shared task")
  await expect(card(second, "Shared task")).toBeVisible()
  // The second browser stops hearing from the server, so its next save goes out against a stale revision.
  await second.route("**/api/board", (route) => route.request().method() === "GET" ? route.abort() : route.continue())
  await openCard(second, "Shared task")
  await openCard(page, "Shared task")
  await editor(page).getByRole("textbox", { name: "Title", exact: true }).fill("First editor saved")
  await editor(page).getByRole("button", { name: "Close", exact: true }).click()
  await expect(editor(page)).not.toBeVisible()
  await expect(card(page, "First editor saved")).toBeVisible()
  const secondTitle = editor(second).getByRole("textbox", { name: "Title", exact: true })
  await secondTitle.fill("My retained draft")
  await expect(editor(second).getByRole("alert")).toContainText("changed in another client")
  await expect(secondTitle).toHaveValue("My retained draft")
  // Polling resumes and refreshes the board behind the open draft.
  await second.unroute("**/api/board")
  await expect(titles(second)).toHaveText(["First editor saved"])
  await expect(secondTitle).toHaveValue("My retained draft")
  await editor(second).getByRole("button", { name: "Save now", exact: true }).click()
  await expect(editor(second).getByRole("status")).toHaveText("Saved")
  await editor(second).getByRole("button", { name: "Close", exact: true }).click()
  await expect(editor(second)).not.toBeVisible()
  await expect(card(page, "My retained draft")).toBeVisible()
  await openCard(second, "My retained draft")
  await choose(editor(second), "Status", "Doing")
  await editor(second).getByRole("button", { name: "Close", exact: true }).click()
  await expect(titles(page, "doing")).toHaveText(["My retained draft"])
  await page.reload()
  await expect(titles(page, "doing")).toHaveText(["My retained draft"])
  await openCard(page, "My retained draft")
  await editor(page).getByRole("button", { name: "Archive task", exact: true }).click()
  await expect(editor(page)).not.toBeVisible()
  await expect(second.locator(".agora-card")).toHaveCount(0)
  await openBoardAction(second, "Archive (1)")
  await second.getByRole("button", { name: "Restore My retained draft", exact: true }).click()
  await expect(page.locator(".agora-card")).toHaveCount(1)
  await openCard(page, "My retained draft")
  await editor(page).getByRole("button", { name: "Archive task", exact: true }).click()
  await expect(second.getByRole("button", { name: "Delete My retained draft permanently", exact: true })).toBeVisible()
  await second.getByRole("button", { name: "Delete My retained draft permanently", exact: true }).click()
  await second.getByRole("dialog").getByRole("button", { name: "Delete permanently" }).click()
  await board(page).getByRole("button", { name: "Board actions", exact: true }).click()
  await expect(page.getByRole("button", { name: "Archive (0)", exact: true })).toBeVisible()
  await secondContext.close()
})

test("failed network saves retain drafts and pending saves cannot be dismissed", async ({ page }) => {
  const dialog = await startCard(page, "Survives failure")
  await page.route("**/api/board", async (route) => {
    if (route.request().method() === "POST") await route.abort()
    else await route.continue()
  })
  await dialog.getByRole("button", { name: "Create task", exact: true }).click()
  await expect(dialog.getByRole("alert")).toBeVisible()
  await expect(dialog.getByRole("textbox", { name: "Title", exact: true })).toHaveValue("Survives failure")
  await page.unroute("**/api/board")
  let release!: () => void
  const gate = new Promise<void>((resolve) => { release = resolve })
  await page.route("**/api/board", async (route) => {
    if (route.request().method() === "POST") await gate
    await route.continue()
  })
  await dialog.getByRole("button", { name: "Create task", exact: true }).click()
  await expect(dialog.getByRole("button", { name: "Create task", exact: true })).toBeDisabled()
  await page.keyboard.press("Escape")
  await expect(dialog).toBeVisible()
  release()
  await expect(dialog).not.toBeVisible()
  await page.unroute("**/api/board")
  await page.reload()
  await expect(card(page, "Survives failure")).toBeVisible()
})

test("shared keyboard drag reorder persists and mobile board remains usable", async ({ page }) => {
  await addCard(page, "Order first")
  await addCard(page, "Order second")
  await expect(titles(page, "todo")).toHaveText(["Order first", "Order second"])
  const handle = page.getByRole("button", { name: "Drag Order second", exact: true })
  await handle.focus()
  await page.keyboard.press("Space", { delay: 100 })
  await expect(handle).toHaveAttribute("aria-pressed", "true")
  await page.keyboard.press("ArrowUp", { delay: 100 })
  await page.keyboard.press("Space", { delay: 100 })
  await expect(handle).not.toHaveAttribute("aria-pressed", "true")
  await expect(titles(page, "todo")).toHaveText(["Order second", "Order first"])
  await page.reload()
  await expect(titles(page, "todo")).toHaveText(["Order second", "Order first"])
  await page.setViewportSize({ width: 390, height: 844 })
  await openCard(page, "Order second")
  await expect(editor(page).getByRole("textbox", { name: "Title", exact: true })).toHaveValue("Order second")
  await editor(page).getByRole("button", { name: "Close", exact: true }).click()
  await expect(editor(page)).not.toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
